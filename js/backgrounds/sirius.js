// ---- ????????? ???????? ???? ----
const waves = [];

function initWaves(W, H) {
  waves.length = 0;
  const seaTop    = H * 0.40;   // ???? ???? = ????? ?????????
  const seaBottom = H * 0.60;   // ??? ???? = ????? ??????

  // ??? ???? ????-«?????», ???????? ? ?????? ?????????
  for (let layer = 0; layer < 3; layer++) {
    const y = seaTop + (seaBottom - seaTop) * (layer + 1) / 4;
    const speed = 0.15 + layer * 0.12;
    const segments = [];
    const count = 8 + layer * 3;
    for (let i = 0; i < count; i++) {
      segments.push({
        x: (i / count) * W * 1.4 - W * 0.2,
        w: W * (0.03 + Math.random() * 0.06),
        alpha: 0.15 + layer * 0.1,
        phase: Math.random() * Math.PI * 2,
      });
    }
    waves.push({ y, speed, segments });
  }
}

// ?????? — ????????? ????? ??????? ????? ? ??????
const crests = [];
function initCrests(W, H) {
  crests.length = 0;
  const seaTop    = H * 0.40;
  const seaBottom = H * 0.60;
  for (let i = 0; i < 30; i++) {
    crests.push({
      x: Math.random() * W,
      y: seaTop + Math.random() * (seaBottom - seaTop),
      w: 8 + Math.random() * 24,
      speed: 0.4 + Math.random() * 0.8,
      alpha: 0.2 + Math.random() * 0.5,
    });
  }
}

export function drawSirius(ctx, W, H, t = 0) {
  const horizonY = H * 0.40;   // ???????? (???? ????)
  const shoreY   = H * 0.60;   // ?????? ???? (?????? ?????)

  if (waves.length === 0) {
    initWaves(W, H);
    initCrests(W, H);
  }

  // ============================================================
  //  1. ???? — 0%..40%
  // ============================================================
  const sky = ctx.createLinearGradient(0, 0, 0, horizonY);
  sky.addColorStop(0,    '#1a2a5a');
  sky.addColorStop(0.3,  '#4a3a7a');
  sky.addColorStop(0.55, '#a8506a');
  sky.addColorStop(0.78, '#e88a4a');
  sky.addColorStop(0.92, '#f8b060');
  sky.addColorStop(1,    '#ffd88a');
  ctx.fillStyle = sky;
  ctx.fillRect(0, 0, W, horizonY);

  // ?????? — ?????????? ? ????
  const sunX = W * 0.5;
  const sunY = horizonY;                 // ????? ?????? ?? ????? ?????????
  const sunR = Math.min(W, H) * 0.075;

  // ???? ?????? ??????
  const halo = ctx.createRadialGradient(sunX, sunY, 0, sunX, sunY, sunR * 7);
  halo.addColorStop(0,   'rgba(255,240,180,0.9)');
  halo.addColorStop(0.2, 'rgba(255,190,110,0.55)');
  halo.addColorStop(0.55,'rgba(255,120,60,0.2)');
  halo.addColorStop(1,   'rgba(255,100,40,0)');
  ctx.fillStyle = halo;
  ctx.beginPath();
  ctx.arc(sunX, sunY, sunR * 7, 0, Math.PI * 2);
  ctx.fill();

  // ??????? ???????? ?????? (? ????)
  ctx.save();
  ctx.beginPath();
  ctx.rect(0, 0, W, horizonY);
  ctx.clip();

  const sunGrad = ctx.createRadialGradient(
    sunX, sunY - sunR * 0.3, 0,
    sunX, sunY, sunR,
  );
  sunGrad.addColorStop(0,   '#fff6c8');
  sunGrad.addColorStop(0.5, '#ffdf90');
  sunGrad.addColorStop(1,   '#ffb050');
  ctx.fillStyle = sunGrad;
  ctx.beginPath();
  ctx.arc(sunX, sunY, sunR, 0, Math.PI * 2);
  ctx.fill();
  ctx.restore();

  // ============================================================
  //  2. ???? — 40%..60% (?????????????)
  // ============================================================
  const sea = ctx.createLinearGradient(0, horizonY, 0, shoreY);
  sea.addColorStop(0,   '#5a3a6a');
  sea.addColorStop(0.3, '#3a3a6a');
  sea.addColorStop(0.7, '#1e3a5a');
  sea.addColorStop(1,   '#0e2a48');
  ctx.fillStyle = sea;
  ctx.fillRect(0, horizonY, W, shoreY - horizonY);

  // ??????? ?? ?????? ?? ???? (???????????? ??????)
  const sunPath = ctx.createLinearGradient(sunX - W * 0.09, 0, sunX + W * 0.09, 0);
  sunPath.addColorStop(0,   'rgba(255,220,140,0)');
  sunPath.addColorStop(0.5, 'rgba(255,220,140,0.5)');
  sunPath.addColorStop(1,   'rgba(255,220,140,0)');
  ctx.fillStyle = sunPath;
  ctx.fillRect(sunX - W * 0.09, horizonY, W * 0.18, shoreY - horizonY);

  // ?????? ???????? ?????? (? ????) — ? ??????????
  ctx.save();
  ctx.beginPath();
  ctx.rect(0, horizonY, W, shoreY - horizonY);
  ctx.clip();

  // ????????? — ?????????? ?????? ? ??????????
  const reflW = sunR * (1 + Math.sin(t * 0.8) * 0.05);
  const reflH = sunR * 0.55;
  const reflGrad = ctx.createRadialGradient(
    sunX, horizonY + reflH * 0.2, 0,
    sunX, horizonY + reflH * 0.2, reflW,
  );
  reflGrad.addColorStop(0,   'rgba(255,220,140,0.85)');
  reflGrad.addColorStop(0.6, 'rgba(255,170,80,0.35)');
  reflGrad.addColorStop(1,   'rgba(255,120,40,0)');
  ctx.fillStyle = reflGrad;
  ctx.beginPath();
  ctx.ellipse(sunX, horizonY + reflH * 0.15, reflW, reflH, 0, 0, Math.PI * 2);
  ctx.fill();

  // ????????? ????????? ??????????????? ????????? — «????????»
  ctx.fillStyle = sea;
  for (let i = 0; i < 10; i++) {
    const yy = horizonY + i * (shoreY - horizonY) / 12;
    const wobble = Math.sin(t * 1.5 + i * 1.1) * 4;
    const gapY = yy + wobble;
    const gapH = 1 + (i % 2) * 1.5;
    ctx.fillRect(sunX - reflW, gapY, reflW * 2, gapH);
  }
  ctx.restore();

  // ---- ????????????? ???? ???? ----
  waves.forEach(layer => {
    // ?????? ?????????????? «???????» ????, ???????? ????
    layer.segments.forEach(seg => {
      // ???????? ?? X ? ??????????? ?? t
      seg.x += seg.speed;
      // ???????????
      const xWrapped = ((seg.x + W * 0.2) % (W * 1.4)) - W * 0.2;

      // ?????? ???????????? ???????????
      const yWobble = Math.sin(t * 1.2 + seg.phase) * 1.5;

      // ???? ??????? — ?????? ? ??????
      const dx = Math.abs(xWrapped - sunX) / (W * 0.5);
      const warmth = Math.max(0, 1 - dx);
      const r = Math.round(180 + warmth * 75);
      const g = Math.round(200 + warmth * 40);
      const b = Math.round(230 - warmth * 90);
      const a = seg.alpha * (0.6 + warmth * 0.4);

      ctx.fillStyle = `rgba(${r}, ${g}, ${b}, ${a})`;
      ctx.fillRect(xWrapped, layer.y + yWobble, seg.w, 1.5);
    });
  });

  // ---- ??????-«???????» ----
  crests.forEach(c => {
    c.x += c.speed;
    if (c.x > W + 30) c.x = -30;

    // ????? ? ?????? — ????????
    const depth = (c.y - horizonY) / (shoreY - horizonY); // 0..1
    const alpha = c.alpha * (0.4 + depth * 0.6);

    ctx.strokeStyle = `rgba(255,240,220,${alpha})`;
    ctx.lineWidth = 1 + depth;
    ctx.lineCap = 'round';
    ctx.beginPath();
    ctx.moveTo(c.x, c.y);
    ctx.lineTo(c.x + c.w, c.y);
    ctx.stroke();
  });

  // ?????? ????????? ??????????? ????? ?????? (??????????)
  const surfacePulse = 0.25 + Math.sin(t * 1.3) * 0.08;
  const surfGrad = ctx.createRadialGradient(
    sunX, horizonY, 0,
    sunX, horizonY, W * 0.35,
  );
  surfGrad.addColorStop(0, `rgba(255,200,120,${surfacePulse})`);
  surfGrad.addColorStop(1, 'rgba(255,140,60,0)');
  ctx.fillStyle = surfGrad;
  ctx.beginPath();
  ctx.arc(sunX, horizonY, W * 0.35, 0, Math.PI * 2);
  ctx.fill();

  // ============================================================
  //  3. ???????? ???? — 60%..100%
  // ============================================================
  // ???????? ??? — ?????? ????-??????????
  const beach = ctx.createLinearGradient(0, shoreY, 0, H);
  beach.addColorStop(0,    '#8a7460');
  beach.addColorStop(0.25, '#6a5540');
  beach.addColorStop(0.6,  '#4a3a2a');
  beach.addColorStop(1,    '#1e140a');
  ctx.fillStyle = beach;
  ctx.beginPath();
  ctx.moveTo(0, shoreY + H * 0.005);
  ctx.quadraticCurveTo(W * 0.5, shoreY - H * 0.01, W, shoreY + H * 0.01);
  ctx.lineTo(W, H);
  ctx.lineTo(0, H);
  ctx.closePath();
  ctx.fill();

  // ---- ?????? ???? (??????? ?????? ??????) ----
  const foamGrad = ctx.createLinearGradient(0, shoreY - H * 0.01, 0, shoreY + H * 0.02);
  foamGrad.addColorStop(0,   'rgba(255,250,235,0)');
  foamGrad.addColorStop(0.5, 'rgba(255,250,235,0.8)');
  foamGrad.addColorStop(1,   'rgba(255,250,235,0)');
  ctx.fillStyle = foamGrad;
  ctx.beginPath();
  ctx.moveTo(0, shoreY + H * 0.015);
  ctx.quadraticCurveTo(W * 0.5, shoreY, W, shoreY + H * 0.02);
  ctx.lineTo(W, shoreY + H * 0.03);
  ctx.quadraticCurveTo(W * 0.5, shoreY + H * 0.012, 0, shoreY + H * 0.028);
  ctx.closePath();
  ctx.fill();

  // ---- ?????? ----
  // ????????????????? «???» — ?????? ????? ????????? ????????
  // ? ?????? ???????? ? ??????, ????? ???????? ???????? ??????.
  const pebbleCount = Math.floor((W * (H - shoreY)) / 180);
  for (let i = 0; i < pebbleCount; i++) {
    // ??????????????? ?????????? ??? Math.random — ????? ??? ???????????
    // (??? ???????? ????) ?????? ?? ???????
    const r1 = ((i * 9301 + 49297) % 233280) / 23328;
    const r2 = ((i * 4523 + 7919)  % 246801) / 246801;
    const r3 = ((i * 7723 + 233)   % 189123) / 189123;

    const px = r1 * W;
    // ??? ???? (????? ? ???????) — ??? ?????? ??????
    const depth = r2;
    const py = shoreY + H * 0.01 + depth * (H - shoreY - H * 0.01);

    // ?????? ??????? ?? ??????? (???????????)
    const sizeBase = 2 + depth * 9;
    const size = sizeBase * (0.6 + r3 * 0.8);

    // ???? — ????-?????????? ????????
    const tone = r3;
    const base = 50 + tone * 60;
    const warm = 20 + depth * 25;
    const r = Math.round(base + warm);
    const g = Math.round(base + warm * 0.7);
    const b = Math.round(base + warm * 0.4);

    // ???? ??? ????????
    ctx.fillStyle = 'rgba(0,0,0,0.35)';
    ctx.beginPath();
    ctx.ellipse(px + 1, py + 1.5, size, size * 0.6, 0, 0, Math.PI * 2);
    ctx.fill();

    // ??? ???????
    ctx.fillStyle = `rgb(${r}, ${g}, ${b})`;
    ctx.beginPath();
    ctx.ellipse(px, py, size, size * 0.65, 0, 0, Math.PI * 2);
    ctx.fill();

    // ???? ?????? (?????? ?? ??????)
    ctx.fillStyle = `rgba(255, 200, 140, ${0.1 + depth * 0.25})`;
    ctx.beginPath();
    ctx.ellipse(px - size * 0.25, py - size * 0.25, size * 0.5, size * 0.3, 0, 0, Math.PI * 2);
    ctx.fill();
  }

  // ---- ?????? ???????? ?? ????? ?????, ????? ?? ????????? ----
  const vignette = ctx.createLinearGradient(0, H * 0.75, 0, H);
  vignette.addColorStop(0, 'rgba(0,0,0,0)');
  vignette.addColorStop(1, 'rgba(0,0,0,0.55)');
  ctx.fillStyle = vignette;
  ctx.fillRect(0, H * 0.75, W, H * 0.25);

  // ---- ?????? ????????? ?? ?????? ?? ??????? ????? ????? ----
  const beachGlow = ctx.createRadialGradient(
    sunX, shoreY, 0,
    sunX, shoreY, W * 0.5,
  );
  beachGlow.addColorStop(0, 'rgba(255,180,90,0.25)');
  beachGlow.addColorStop(1, 'rgba(255,140,60,0)');
  ctx.fillStyle = beachGlow;
  ctx.beginPath();
  ctx.arc(sunX, shoreY, W * 0.5, 0, Math.PI * 2);
  ctx.fill();
}