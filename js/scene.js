export const MEMBER_TO_GROUP = (() => {
  const map = {};
  for (const [gid, members] of Object.entries(GROUP_MEMBERS)) {
    for (const m of members) map[m.id] = gid;
  }
  return map;
})();

export function getHeadPos(id) {
  const slots = getSlots();

  // --- 1. ??????? ???????? ???????? ?????? ---
  const s = slots[id];
  if (s && !s.members) {
    const headOffset = HEAD_OFFSETS[id] || 130;
    return { x: s.x, y: s.y - headOffset * s.s };
  }

  // --- 2. ???????? ?????? ---
  for (const [gid, members] of Object.entries(GROUP_MEMBERS)) {
    const m = members.find(m => m.id === id);
    if (!m) continue;
    const g = slots[gid];
    if (!g) return null;

    const x = g.x + m.dx * g.s;
    const y = g.y - 130 * g.s;
    return { x, y };
  }

  return null;
}