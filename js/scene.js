export function scene() {
  // ?????????, ???????????? ?? ?????
  const isPortrait = H > W;
  const isMobile = W < 720;

  // ?? ????????? — ?????? ??????? ???????????? min(W, H),
  // ?? ? ???????? ?? ??, ??? ??????????????? ????? ????.
  let scale;
  if (isMobile) {
    // ?? ???????? ??????? ??????? ?? ??????, ? ?? ?? min(W, H),
    // ????? ?? ??????? ?????? ?????? ????? ?????????????????.
    scale = W / 600;
  } else {
    scale = Math.min(W, H) / 650;
  }

  // ?? ???????????? ???????? ???????? ????? ???? ????,
  // ????? ?????? ? ????????? ?? ??????? ??? ?????? ????????.
  const fireYRatio  = isPortrait && isMobile ? 0.70 : 0.79;
  const logYRatio   = isPortrait && isMobile ? 0.78 : 0.87;
  const logHRatio   = isMobile ? 0.07 : 0.09;

  return {
    cx: W / 2,
    fireY: H * fireYRatio,
    logY:  H * logYRatio,
    logH:  H * logHRatio,
    scale,
    isMobile,
    isPortrait,
  };
}

