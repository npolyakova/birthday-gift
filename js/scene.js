export function initButtons(onChange) {
  document.querySelectorAll('#ui button').forEach(btn => {
    btn.addEventListener('click', () => {
      const id = btn.dataset.id;

      if (id === 'guy1a') {
        shown.guy1a = !shown.guy1a;
        if (shown.guy1a) shown.guy1 = false;
        else shown.guy1 = true;
      } else if (id === 'guy1') {
        shown.guy1 = !shown.guy1;
        if (shown.guy1) shown.guy1a = false;
        else shown.guy1a = true;
      } else {
        shown[id] = !shown[id];
      }
      updateButtons();
      if (onChange) onChange(id);
    });
  });
  updateButtons();
}

export function updateButtons() {
  document.querySelectorAll('#ui button').forEach(btn => {
    const id = btn.dataset.id;
    let on = false;
    if (id === 'guy1')        on = shown.guy1;
    else if (id === 'guy1a')  on = shown.guy1a;
    else                      on = shown[id];
    btn.classList.toggle('on', on);
  });
}

