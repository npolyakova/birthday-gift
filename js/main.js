// js/main.js
import {
  ctx, W, H, shown,
  initButtons, getSlots, getHeadPos,
  backgroundState, initBackgroundButtons,
} from './scene.js';
import {
  drawFire, drawAmbientGlow, drawParticles, tickFire, drawBenchLog,
} from './fire.js';
import {
  drawGuySummer, drawGuyAutumn, drawGirlRed, drawCat,
} from './characters.js';
import {
  drawFriendGroup, drawFamilyGroup, drawUniGroup,
} from './groups.js';
import { updateSpeech, drawSpeech } from './speech.js';
import { backgrounds } from './backgrounds/index.js';
import { initUiToggle } from './ui.js';

initUiToggle();
initButtons();
initBackgroundButtons();

// ????????-?????: ?????? ??? ???? ???, ????? ????????
const bgCanvas = document.createElement('canvas');
const bgCtx = bgCanvas.getContext('2d');

function renderBackground() {
  bgCanvas.width = W;
  bgCanvas.height = H;
  const fn = backgrounds[backgroundState.current];
  if (fn) fn(bgCtx, W, H);
  backgroundState.dirty = false;
}

// ????????: ??????? ?? ???????? ?? ?????
const isVisible = (id) => {
  if (id === 'guy1')  return shown.guy1;
  if (id === 'guy1a') return shown.guy1a;
  return !!shown[id];
};

let lastFrameTime = performance.now();

function loop() {
  const now = performance.now();
  const dt = (now - lastFrameTime) / 1000;
  lastFrameTime = now;

  // ?????????????? ???, ???? ???????? ??? ????????? ??????
  if (backgroundState.dirty || bgCanvas.width !== W || bgCanvas.height !== H) {
    renderBackground();
  }

  // ???????? ???
  ctx.drawImage(bgCanvas, 0, 0);

  // ?????? ???????? ?????? + ???????
  drawAmbientGlow();
  drawFire();
  drawParticles();

  // ?????????
  const slots = getSlots();

  if (shown.guy1)   drawGuySummer(slots.guySummer.x, slots.guySummer.y, slots.guySummer.s);
  if (shown.guy1a)  drawGuyAutumn(slots.guyAutumn.x, slots.guyAutumn.y, slots.guyAutumn.s);
  if (shown.girl)   drawGirlRed(slots.girl.x, slots.girl.y, slots.girl.s);
  if (shown.group)  drawFriendGroup(slots.group.x, slots.group.y, slots.group.s);
  if (shown.family) drawFamilyGroup(slots.family.x, slots.family.y, slots.family.s);
  if (shown.uni)    drawUniGroup(slots.uni.x, slots.uni.y, slots.uni.s);

  // ?????? ?????? ???
  drawBenchLog(0.43, W*0.02);
  drawBenchLog(0.3, W*0.4);
  drawBenchLog(0.4, W*0.6);

  // ????? — ?????? ??????
  if (shown.cat) drawCat(slots.cat.x, slots.cat.y, slots.cat.s);

  // ---- ??????? ----
  // ????????? ?????? (?????????/????????????), ?? ?? ?????? ????
  updateSpeech(dt, isVisible);

  // ??????? ?????? — ????? ??????
  tickFire();

  // ---- ??????? — ????? ????????? ?????, ?????? ????? ----
  drawSpeech((slotId) => getHeadPos(slotId));

  requestAnimationFrame(loop);
}

loop();